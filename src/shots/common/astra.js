const GAP = 0.35;

// 排版：返回每个节点与连线的字标坐标（左下为原点）
export function layoutWord(word = 'ASTRA') {
  const nodes = [], segs = [];
  let x = 0;
  [...word.toUpperCase()].forEach((ch, li) => {
    const g = G[ch] || G[' '];
    const base = nodes.length;
    g.n.forEach(([nx, ny], ni) => nodes.push({ li, ni, x: x + nx, y: ny }));
    g.s.forEach(([a, b]) => segs.push({ li, a: base + a, b: base + b }));
    x += (g.w ?? 0.7) + GAP;
  });
  return { nodes, segs, width: x - GAP };
}
